#!/usr/bin/env node
/**
 * Fetches legacy ghazal glossary HTML and writes src/lib/data/glossary-terms.ts
 * Source: shahzebqazi/kashmiri-language-poetry legacy/pages/02-ghazals.html
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const SOURCE_URL =
	'https://raw.githubusercontent.com/shahzebqazi/kashmiri-language-poetry/main/legacy/pages/02-ghazals.html';
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/lib/data/glossary-terms.ts');

function slugify(text) {
	return text
		.toLowerCase()
		.normalize('NFD')
		.replace(/[\u0300-\u036f]/g, '')
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-|-$/g, '')
		.slice(0, 80);
}

function stripTags(html) {
	return html
		.replace(/<br\s*\/?>/gi, '\n')
		.replace(/<[^>]+>/g, '')
		.replace(/\s+/g, ' ')
		.trim();
}

function extractSpans(html, langs) {
	const found = [];
	for (const lang of langs) {
		const re = new RegExp(`<span[^>]*lang=["']${lang}["'][^>]*>([\\s\\S]*?)</span>`, 'gi');
		let m;
		while ((m = re.exec(html))) {
			const text = stripTags(m[1]);
			if (text) found.push({ lang, text });
		}
	}
	return found;
}

function parseDtDd(html) {
	const terms = [];
	const dlMatch = html.match(/<dl class="glossary">([\s\S]*?)<\/dl>/i);
	if (!dlMatch) return terms;
	const block = dlMatch[1];
	const pairRe = /<dt>([\s\S]*?)<\/dt>\s*<dd>([\s\S]*?)<\/dd>/gi;
	let pair;
	while ((pair = pairRe.exec(block))) {
		const label = stripTags(pair[1]);
		const ddHtml = pair[2];
		const definition = stripTags(ddHtml);
		if (!label || !definition) continue;

		const urSpans = extractSpans(ddHtml, ['ur', 'ur-Latn']);
		const arSpans = extractSpans(ddHtml, ['ar', 'ar-Latn']);

		const term = {
			slug: slugify(label),
			category: 'ghazal',
			english: { label, definition }
		};

		if (urSpans.length || arSpans.length) {
			term.urdu = {
				label: urSpans.find((s) => s.lang === 'ur-Latn')?.text,
				script: arSpans.find((s) => s.lang === 'ar')?.text,
				definition: urSpans.map((s) => s.text).join(' · ') || undefined
			};
			if (!term.urdu.label && !term.urdu.script && !term.urdu.definition) {
				delete term.urdu;
			}
		}

		terms.push(term);
	}
	return terms;
}

function parseTopicSections(html) {
	const terms = [];
	const sectionRe =
		/<section[^>]*id="([^"]+)"[^>]*>[\s\S]*?<h2[^>]*>([\s\S]*?)<\/h2>[\s\S]*?<p class="lede">([\s\S]*?)<\/p>/gi;
	let m;
	while ((m = sectionRe.exec(html))) {
		const id = m[1];
		const label = stripTags(m[2]);
		const definition = stripTags(m[3]);
		if (!label || !definition) continue;
		terms.push({
			slug: id,
			category: 'topic',
			english: { label, definition },
			urdu: (() => {
				const urSpans = extractSpans(m[3], ['ur', 'ur-Latn']);
				const arSpans = extractSpans(m[3], ['ar', 'ar-Latn']);
				if (!urSpans.length && !arSpans.length) return undefined;
				return {
					label: urSpans.find((s) => s.lang === 'ur-Latn')?.text,
					script: arSpans.find((s) => s.lang === 'ar')?.text,
					definition: urSpans.map((s) => s.text).join(' · ') || undefined
				};
			})()
		});
	}
	return terms;
}

async function main() {
	const res = await fetch(SOURCE_URL);
	if (!res.ok) throw new Error(`Fetch failed: ${res.status} ${SOURCE_URL}`);
	const html = await res.text();
	const terms = [...parseDtDd(html), ...parseTopicSections(html)];

	const seen = new Set();
	const unique = terms.filter((t) => {
		if (seen.has(t.slug)) return false;
		seen.add(t.slug);
		return true;
	});

	const body = `import type { GlossaryTerm } from '$lib/types/glossary';

/** Generated by scripts/import-glossary.mjs — run npm run import:glossary */
export const ghazalTerms: GlossaryTerm[] = ${JSON.stringify(unique, null, '\t')};
`;

	await writeFile(OUT, body, 'utf8');
	console.log(`Wrote ${unique.length} ghazal glossary terms to ${OUT}`);
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
